-- 중앙 센터 Supabase 데이터베이스 초기 설정
-- Supabase Dashboard > SQL Editor에서 전체 실행

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.notices (
  id bigint generated by default as identity primary key,
  category text not null default '안내',
  title text not null,
  body text not null,
  published boolean not null default true,
  author_id uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.notices enable row level security;

create or replace function public.is_central_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = (select auth.uid()) and role = 'admin'
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, role) values (new.id, 'user')
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

-- 사용자는 본인 프로필만 조회할 수 있습니다.
drop policy if exists "read own profile" on public.profiles;
create policy "read own profile" on public.profiles
for select to authenticated
using (id = (select auth.uid()));

-- 공개된 공지는 누구나 조회할 수 있고, 관리자는 비공개 공지도 조회할 수 있습니다.
drop policy if exists "read published notices" on public.notices;
create policy "read published notices" on public.notices
for select to anon, authenticated
using (published = true or public.is_central_admin());

-- 공지 등록/수정/삭제는 관리자만 가능합니다.
drop policy if exists "admin insert notices" on public.notices;
create policy "admin insert notices" on public.notices
for insert to authenticated
with check (public.is_central_admin() and author_id = (select auth.uid()));

drop policy if exists "admin update notices" on public.notices;
create policy "admin update notices" on public.notices
for update to authenticated
using (public.is_central_admin())
with check (public.is_central_admin());

drop policy if exists "admin delete notices" on public.notices;
create policy "admin delete notices" on public.notices
for delete to authenticated
using (public.is_central_admin());

grant usage on schema public to anon, authenticated;
grant select on public.notices to anon, authenticated;
grant insert, update, delete on public.notices to authenticated;
grant select on public.profiles to authenticated;
grant usage, select on sequence public.notices_id_seq to authenticated;

